# Writes src/ui/spriteBounds.ts: for each battle sprite, the transparent rows above the visible
# body (its head) at native size. Rerun after adding or changing sprites:
#   python3 scripts/spriteBounds.py
import glob, os
from PIL import Image
root = os.path.join(os.path.dirname(__file__), '..', 'src')
rows = []
for f in sorted(glob.glob(os.path.join(root, 'assets', 'monsters', '*.webp')) + glob.glob(os.path.join(root, 'assets', 'heroes', '*.webp'))):
    im = Image.open(f)
    b = im.getchannel('A').getbbox()
    rows.append(f"    '{os.path.basename(f)[:-5]}': {b[1]},")
open(os.path.join(root, 'ui', 'spriteBounds.ts'), 'w').write(
    "// Generated by scripts/spriteBounds.py: empty pixel rows above each sprite's visible body.\n"
    "// Sprites stand on their image's bottom edge, so this is all that is needed to find the head.\n"
    "export const spriteHeadroom: Record<string, number> = {\n" + "\n".join(rows) + "\n};\n")
